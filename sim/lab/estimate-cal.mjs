#!/usr/bin/env node
// B1 (docs/board/TASKS.md "Build settings"): how far the lab's model (public/lab/predict.js) is from real runs,
// as ratios real / predicted for wall time and API-equivalent cost, over every finished lab run
// (public/lab/runs.jsonl, status done). Writes public/lab/estimate-cal.js, which public/lab/estimate.js uses
// to turn one prediction into an honest range. Rerun after new runs land:  node sim/lab/estimate-cal.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { predict, SIM_VERSION } from '../../public/lab/predict.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const runs = readFileSync(join(ROOT, 'public/lab/runs.jsonl'), 'utf8').trim().split('\n').map(JSON.parse)
  .filter((r) => r.status === 'done' && r.timings?.wallS && r.cost?.apiUsdStd);
const rows = runs.map((r) => {
  const p = predict(r.variant || {}, r.scenario, { seeds: 30, baseline: r.baseline });
  return { id: r.id, key: r.variantKey, scenario: r.scenario, baseline: r.baseline || null, policy: r.baseline ? r.baseline : r.variant.policy,
    wall: +(r.timings.wallS / p.wallS).toFixed(3), cost: +(r.cost.apiUsdStd / p.apiUsdStd).toFixed(3) };
});
// Builds use land-by-intent or one agent alone; policy github (a lab-only baseline) is off by ~3x on time
// and would widen every band, so it is left out of the bands (and counted separately).
const used = rows.filter((r) => r.policy !== 'github');
const q = (xs, p) => { const s = [...xs].sort((a, b) => a - b); const i = (s.length - 1) * p; const lo = Math.floor(i); return +(s[lo] + (s[Math.ceil(i)] - s[lo]) * (i - lo)).toFixed(2); };
const band = (k) => ({ p10: q(used.map((r) => r[k]), 0.1), p50: q(used.map((r) => r[k]), 0.5), p90: q(used.map((r) => r[k]), 0.9) });
const cal = { generated: new Date().toISOString(), simVersion: SIM_VERSION, runs: used.length, leftOut: rows.length - used.length,
  wall: band('wall'), cost: band('cost'),
  byShape: { alone: used.filter((r) => r.baseline === 'opus-alone').length, team: used.filter((r) => !r.baseline).length },
  rows: used.map(({ id, key, scenario, wall, cost }) => ({ id, key, scenario, wall, cost })) };
writeFileSync(join(ROOT, 'public/lab/estimate-cal.js'), `// Generated by sim/lab/estimate-cal.mjs: real / predicted over finished lab runs. Do not edit by hand.\nexport default ${JSON.stringify(cal, null, 1)};\n`);
console.log(`runs ${cal.runs} (left out ${cal.leftOut} github) wall ${JSON.stringify(cal.wall)} cost ${JSON.stringify(cal.cost)}`);
