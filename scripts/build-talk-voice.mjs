#!/usr/bin/env node
// Bundle the browser voice client (src/client/talkvoice-entry.ts) into a string the
// Worker serves at /talk-voice.js. Run after upgrading `agents`, then commit:
//   node scripts/build-talk-voice.mjs
import { build } from 'esbuild';
import fs from 'node:fs';
const r = await build({ entryPoints: ['src/client/talkvoice-entry.ts'], bundle: true, format: 'iife', platform: 'browser', target: 'es2020', minify: true, write: false, legalComments: 'none' });
const js = r.outputFiles[0].text;
fs.writeFileSync('src/talkvoicejs.gen.ts', `// GENERATED by scripts/build-talk-voice.mjs from src/client/talkvoice-entry.ts (agents ${JSON.parse(fs.readFileSync('node_modules/agents/package.json', 'utf8')).version}). Do not edit.\nexport const TALK_VOICE_JS = ${JSON.stringify(js)};\n`);
console.log(`src/talkvoicejs.gen.ts: ${(js.length / 1024).toFixed(1)} KB`);
